"""Native ThirdPartyNotices.txt generator and verifier using importlib.metadata."""

import importlib.metadata as meta
import tomllib
from pathlib import Path


def read_text_or_empty(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError:
        return ""


def extract_license_text(dist: meta.Distribution) -> str:
    if dist.files:
        for f in dist.files:
            name = Path(str(f)).name.lower()
            if name.startswith(("license", "copying")):
                try:
                    raw = Path(dist.locate_file(f)).read_text(encoding="utf-8", errors="replace")
                    cleaned = raw.replace("\r\n", "\n").strip()
                    if cleaned:
                        return cleaned
                except OSError:
                    continue
    return ""


def read_project_name(root: Path) -> str:
    try:
        data = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
        return str(data.get("project", {}).get("name", ""))
    except (OSError, tomllib.TOMLDecodeError):
        return ""


def run_notices(root: Path, check_only: bool) -> bool:
    project_name = read_project_name(root)
    rows: list[tuple[str, str, str, str]] = []
    seen: set[str] = set()
    for dist in sorted(meta.distributions(), key=lambda d: (d.metadata["Name"] or "").lower()):
        name = dist.metadata["Name"] or "unknown"
        if name in seen or (project_name and name == project_name):
            continue
        seen.add(name)
        version = dist.version
        lic = dist.metadata.get("License") or dist.metadata.get("License-Expression") or "See license text"
        lic = lic.splitlines()[0].strip() if lic else "See license text"
        rows.append((name, version, lic, extract_license_text(dist)))

    lines = [
        "Third Party Notices",
        "",
        "Generated by python -m tools.xtask notices. Do not edit by hand.",
        f"Python packages installed: {len(rows)}",
    ]
    if rows:
        lines.extend(["", "| Package | Version | License |", "|---|---|---|"])
        for name, ver, lic, _ in rows:
            lines.append(f"| {name} | {ver} | {lic} |")
        for idx, (name, ver, _, text) in enumerate(rows, start=1):
            if text:
                lines.extend([
                    "",
                    f"## License Text {idx}",
                    f"Applies to: {name} {ver}",
                    "",
                    "```text",
                    text,
                    "```",
                ])

    content = "\n".join(lines) + "\n"
    out = root / "ThirdPartyNotices.txt"
    if check_only:
        if read_text_or_empty(out) != content:
            print("FAIL notices: ThirdPartyNotices.txt is out of date (run uv run python -m tools.xtask notices)")
            return False
        print(f"PASS notices ({len(rows)} packages)")
        return True

    out.write_text(content, encoding="utf-8")
    print(f"PASS notices: updated ThirdPartyNotices.txt ({len(rows)} packages)")
    return True
